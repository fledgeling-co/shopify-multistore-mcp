"""
Engine A - hand-authored layered SVG masters for the shopify-multistore-mcp icon options.

Five new directions beside the incumbent "Shopfront row" (design/icon/build_icon.py), each
in a different ground register so the set is a real choice rather than five shades of one idea:

  labelled    saturated jade gel tile + frosted reply bubble; every row starts with a store label
  switchboard dark glass; three lit sockets whose cables merge into one plug
  fanned      porcelain; three translucent shop cards fanned like a hand, overlaps deepen
  tagring     porcelain clay; three labelled store tags on one ring
  monogram    ink tile; an M standing under one jade awning (three shopfronts, one roof)

Values sampled from the corpus before authoring (references/corpus/apple-2026):
  saturated tiles run lighter and greener-shifted at the top (Mail h205 s0.52 -> h223 s0.78);
  dark grounds are charcoal #313131 -> #141414, faintly tinted (the butterfly's navy);
  porcelain runs #FFFFFF -> ~#ECEBEB; gel darks stay saturated in their own hue, never grey
  (Reminders' darkest blue is #406BE7).

Jade sits at h158, away from Shopify's bag green (#95BF47, h85). No bag shapes.
Every master: 1024 full-bleed, squircle as a CLIP, four layers #bg / #mid / #fg / #highlight.
Usage: python3 build_options.py   (writes icon-engineA-<slug>.svg beside this file)
"""

