# ================================================================ 3. fanned shops
FAN_CARD = (236, 330, 38)                # w, h, radius
FAN_CENTRE = (512, 532)                  # centre of the front card
FAN_PIVOT = (512, 800)                   # fan rotates about a point near the cards' foot, like a hand of cards
FAN_ANGLE = 16
FAN_SPREAD = 86                          # side cards also slide outwards so each shows its awning
FAN_OPACITY = 0.82
FAN_TINTS = ((JADE_LIGHT, "#86E8C1", "#2DBB8A"), (JADE, JADE_LIGHT, JADE_DEEP), (JADE_DEEP, "#3BC394", JADE_SHADE))


def fanned():
    defs, bg = tile(PORCELAIN_TOP, PORCELAIN_BOTTOM, rim_opacity=0.75)
    w, h, r = FAN_CARD
    cx, cy = FAN_CENTRE
    x0, y0 = cx - w / 2, cy - h / 2
    awning_h = h * 0.28
    for i, (base, top, bottom) in enumerate(FAN_TINTS):
        defs += gel(f"card{i}", top, base, bottom)
    defs += f"""
  <linearGradient id="awning" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#FFFFFF" stop-opacity="0.75"/><stop offset="1" stop-color="#FFFFFF" stop-opacity="0.35"/></linearGradient>
  <clipPath id="cardclip"><rect x="{x0}" y="{y0}" width="{w}" height="{h}" rx="{r}"/></clipPath>"""

    def card(i, angle):
        px, py = FAN_PIVOT
        aw = f"M{x0},{y0} L{x0 + w},{y0} L{x0 + w},{y0 + awning_h} {scallops(x0, x0 + w, y0 + awning_h, 30)} Z"
        dw, dh = w * 0.30, h * 0.36
        dx = cx - dw / 2
        door = f"M{dx},{y0 + h} L{dx},{y0 + h - dh + dw / 2} A{dw / 2},{dw / 2} 0 0 1 {dx + dw},{y0 + h - dh + dw / 2} L{dx + dw},{y0 + h} Z"
        return f"""
    <g transform="translate({FAN_SPREAD * (angle > 0) - FAN_SPREAD * (angle < 0)},0) rotate({angle} {px} {py})">
      <rect x="{x0}" y="{y0}" width="{w}" height="{h}" rx="{r}" fill="url(#card{i})" fill-opacity="{FAN_OPACITY}"/>
      <g clip-path="url(#cardclip)"><path d="{aw}" fill="url(#awning)"/><path d="{door}" fill="{JADE_SHADE}" opacity="0.55"/></g>
      <rect x="{x0}" y="{y0}" width="{w}" height="{h}" rx="{r}" fill="none" stroke="{JADE_SHADE}" stroke-opacity="0.45" stroke-width="4"/>
      <path d="M{x0 + r},{y0 + 10} L{x0 + w - r},{y0 + 10}" stroke="#FFFFFF" stroke-opacity="0.8" stroke-width="7" stroke-linecap="round"/>
    </g>"""
    mid = f'\n    <ellipse cx="512" cy="{y0 + h + 34}" rx="300" ry="34" fill="#1F7A5E" opacity="0.26" filter="url(#soft)"/>'
    fg = card(0, -FAN_ANGLE) + card(2, FAN_ANGLE) + card(1, 0)
    hi = f'\n    <ellipse cx="{cx}" cy="{y0 + 70}" rx="90" ry="24" fill="#FFFFFF" opacity="0.18" filter="url(#blur8)"/>'
    return svg("fanned", "Fanned shops", defs, bg, mid, fg, hi)


# ================================================================ 4. tag ring
TAG_RING = (512, 262, 88, 34)            # cx, cy, r, stroke  (r01: bigger, heavier ring, as the reference)
TAG = (200, 276, 34)                     # w, h, corner radius  (r01: group ~68% of the tile)
TAG_SPOTS = ((366, 556, 14), (658, 556, -14), (512, 596, 0))   # cx, cy (tag centre), angle; centre last = in front (r03: fan outward so every symbol shows)
TAG_LINK_W = 18                          # r01: each tag hangs on a short link, not a thin cord
TAG_TINTS = (("#2C9C80", JADE_SHADE, "#075446"), ("#CFF8E4", "#9FE9C6", "#5FCFA2"), (JADE_LIGHT, JADE, JADE_DEEP))
TAG_SYMBOL = 0.95
TAG_THICK = 12                           # r02: clay slab depth under each face
TAG_CAST = 0.28                          # r02: shadow a tag casts on the one behind
TAG_RING_CAST = 0.2                       # r04: shadow the ring casts on the tile


def tagring():
    defs, bg = tile(PORCELAIN_TOP, PORCELAIN_BOTTOM, rim_opacity=0.75)
    rcx, rcy, rr, rs = TAG_RING
    w, h, r = TAG
    for i, t in enumerate(TAG_TINTS):
        defs += gel(f"tag{i}", *t)
    defs += gel("ringgel", JADE_LIGHT, JADE, JADE_SHADE)

    def tag(i, cx, cy, angle):
        x0, y0 = cx - w / 2, cy - h / 2
        cut = 46
        body = (f"M{x0 + cut},{y0} L{x0 + w - cut},{y0} L{x0 + w},{y0 + cut} L{x0 + w},{y0 + h - r} "
                f"Q{x0 + w},{y0 + h} {x0 + w - r},{y0 + h} L{x0 + r},{y0 + h} Q{x0},{y0 + h} {x0},{y0 + h - r} "
                f"L{x0},{y0 + cut} Z")
        hole_y = y0 + 40
        # embossed shop symbol on the face: an awning over a door
        sx0, sy0, sw = cx - 46, cy + 4, 92
        sym_aw = f"M{sx0},{sy0} L{sx0 + sw},{sy0} L{sx0 + sw},{sy0 + 24} {scallops(sx0, sx0 + sw, sy0 + 24, 12)} Z"
        sym_body = f"M{sx0 + 8},{sy0 + 34} L{sx0 + sw - 8},{sy0 + 34} L{sx0 + sw - 8},{sy0 + 84} L{sx0 + 8},{sy0 + 84} Z"
        sym_door = f"M{cx - 14},{sy0 + 84} L{cx - 14},{sy0 + 58} A14,14 0 0 1 {cx + 14},{sy0 + 58} L{cx + 14},{sy0 + 84} Z"
        lit, base, dark = TAG_TINTS[i]
        # r02 material: clay thickness (a darker slab under the face), a shadow cast on the tag
        # behind, and the shop symbol embossed in the tag's own hue rather than printed on it.
        return f"""
    <g transform="rotate({angle} {cx} {hole_y})">
      <path d="{body}" fill="#064A3C" opacity="{TAG_CAST}" transform="translate(10,18)" filter="url(#blur8)"/>
      <path d="{body}" fill="{dark}" transform="translate(0,{TAG_THICK})"/>
      <path d="{body}" fill="url(#tag{i})"/>
      <path d="{body}" fill="none" stroke="{dark}" stroke-opacity="0.55" stroke-width="3"/>
      <circle cx="{cx}" cy="{hole_y}" r="17" fill="#F4F4F2"/><circle cx="{cx}" cy="{hole_y}" r="17" fill="none" stroke="#064A3C" stroke-opacity="0.4" stroke-width="4"/>
      <g opacity="{TAG_SYMBOL}" transform="translate(0,4)"><path d="{sym_aw}" fill="{dark}"/><path d="{sym_body}" fill="{dark}" fill-opacity="0.7"/><path d="{sym_door}" fill="{dark}"/></g>
      <g opacity="{TAG_SYMBOL}"><path d="{sym_aw}" fill="{lit}"/><path d="{sym_body}" fill="{lit}" fill-opacity="0.55"/><path d="{sym_door}" fill="{dark}"/></g>
      <path d="M{x0 + cut + 6},{y0 + 10} L{x0 + w - cut - 6},{y0 + 10}" stroke="#FFFFFF" stroke-opacity="0.6" stroke-width="6" stroke-linecap="round"/>
    </g>"""

    def link(i, cx, cy):
        top = (rcx + (cx - rcx) * 0.28, rcy + rr * 0.92)
        eye = (cx, cy - h / 2 + 40)
        tint = TAG_TINTS[i]
        return (f'\n    <path d="M{top[0]:.0f},{top[1]:.0f} L{eye[0]:.0f},{eye[1]:.0f}" stroke="{tint[2]}" stroke-width="{TAG_LINK_W}" stroke-linecap="round"/>'
                f'\n    <path d="M{top[0]:.0f},{top[1]:.0f} L{eye[0]:.0f},{eye[1]:.0f}" stroke="{tint[0]}" stroke-width="{TAG_LINK_W * 0.4:.0f}" stroke-linecap="round" opacity="0.7" transform="translate(-3,-2)"/>')
    cords = "".join(link(i, cx, cy) for i, (cx, cy, a) in ((0, TAG_SPOTS[0]), (1, TAG_SPOTS[1]), (2, TAG_SPOTS[2])))
    # r04: the contact shadow gets a filter region tall enough for its blur; #soft clipped it flat
    defs += '<filter id="pool" x="-30%" y="-250%" width="160%" height="600%"><feGaussianBlur stdDeviation="18"/></filter>'
    mid = (f'\n    <circle cx="{rcx + 8}" cy="{rcy + 16}" r="{rr}" fill="none" stroke="#064A3C" stroke-opacity="{TAG_RING_CAST}" stroke-width="{rs}" filter="url(#blur8)"/>'
           f'\n    <ellipse cx="512" cy="{580 + h / 2 + 30}" rx="260" ry="32" fill="#1F7A5E" opacity="0.26" filter="url(#pool)"/>')
    fg = f"""
    <circle cx="{rcx}" cy="{rcy}" r="{rr}" fill="none" stroke="url(#ringgel)" stroke-width="{rs}"/>{cords}
    <circle cx="{rcx}" cy="{rcy}" r="{rr + rs / 2 - 1.5}" fill="none" stroke="#064A3C" stroke-opacity="0.28" stroke-width="3"/>
    <circle cx="{rcx}" cy="{rcy}" r="{rr - rs / 2 + 1.5}" fill="none" stroke="#064A3C" stroke-opacity="0.22" stroke-width="3"/>""" + "".join(tag(i, *spot) for i, spot in ((0, TAG_SPOTS[0]), (1, TAG_SPOTS[1]), (2, TAG_SPOTS[2])))
    hi = f'\n    <path d="M{rcx - 46},{rcy - 50} A{rr},{rr} 0 0 1 {rcx + 38},{rcy - 56}" fill="none" stroke="#FFFFFF" stroke-opacity="0.75" stroke-width="7" stroke-linecap="round"/>'
    return svg("tagring", "Tag ring", defs, bg, mid, fg, hi)



