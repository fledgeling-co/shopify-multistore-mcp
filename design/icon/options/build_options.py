# ---------------------------------------------------------------- shared tile


def tile(top, bottom, rim="#FFFFFF", rim_opacity=0.7, vignette=0.05):
    """The cushion ground: vertical ramp, edge vignette, inner rim light."""
    defs = f"""
  <linearGradient id="ground" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{top}"/><stop offset="1" stop-color="{bottom}"/></linearGradient>
  <radialGradient id="vignette" cx="0.5" cy="0.42" r="0.72"><stop offset="0.6" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="{vignette}"/></radialGradient>
  <filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="18"/></filter>
  <filter id="blur8" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="8"/></filter>
  <filter id="glow" x="-60%" y="-60%" width="220%" height="220%"><feGaussianBlur stdDeviation="22"/></filter>"""
    bg = f"""
  <g id="bg">
    <rect width="{W}" height="{W}" fill="url(#ground)"/>
    <rect width="{W}" height="{W}" fill="url(#vignette)"/>
    <path d="{SQUIRCLE}" fill="none" stroke="{rim}" stroke-opacity="{rim_opacity}" stroke-width="14"/>
  </g>"""
    return defs, bg


def svg(slug, title, defs, bg, mid, fg, hi):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{W}" viewBox="0 0 {W} {W}">
<!--
  shopify-multistore-mcp icon option "{title}" (Engine A master).
  Generated by build_options.py; edit the constants there, never this file.
  Full-bleed 1024 artwork; the squircle is a CLIP. Layers: #bg / #mid / #fg / #highlight.
-->
<defs>
  <clipPath id="mask"><path d="{SQUIRCLE}"/></clipPath>{defs}
</defs>
<g clip-path="url(#mask)">{bg}
  <g id="mid">{mid}
  </g>
  <g id="fg">{fg}
  </g>
  <g id="highlight">{hi}
  </g>
</g>
</svg>
"""


def gel(id_, top, mid, bottom):
    return (f'<linearGradient id="{id_}" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="{top}"/>'
            f'<stop offset="0.55" stop-color="{mid}"/><stop offset="1" stop-color="{bottom}"/></linearGradient>')


def scallops(x0, x1, y, depth, n=3):
    """Path fragment: n downward scallops from x1 back to x0 along y (for an awning's lower edge)."""
    r = (x1 - x0) / n / 2
    out = []
    for i in range(n):
        end = x1 - (2 * i + 2) * r
        out.append(f"A{r:.1f},{depth:.1f} 0 0 1 {end:.1f},{y:.1f}")
    return " ".join(out)


